"""The zero-shot accuracy tables for the flipquant repository (branch paper-sm120-runs, results/zeroshot6/README.md).
Every number is rounded once to two decimals and comes from one of:
- part X's six models: results/paper_eval/zeroshot6/zeroshot6.json at paper-eval 3c73d2f;
- part X amendment 2 (X2), Qwen3-1.7B and Qwen3-8B: results/paper_eval/zeroshot6_qwen3/zeroshot6_qwen3.json at the
  commit given by --qwen3-commit.

    python zs6_flipquant_readme.py --qwen3-commit <paper-eval commit> --out <flipquant worktree>/results/zeroshot6/README.md
"""
import argparse
import json
import subprocess
from pathlib import Path

SOURCE_COMMIT = "3c73d2f"
SOURCE = "results/paper_eval/zeroshot6/zeroshot6.json"
QWEN3_SOURCE = "results/paper_eval/zeroshot6_qwen3/zeroshot6_qwen3.json"
REPO = Path(__file__).resolve().parents[2]
MODELS = [("llama3.2-1b-instruct", "Llama-3.2-1B-Instruct"), ("llama3.1-8b-instruct", "Llama-3.1-8B-Instruct"),
          ("qwen3-1.7b", "Qwen3-1.7B"), ("qwen3-8b", "Qwen3-8B"),
          ("mistral-7b", "Mistral-7B-Instruct-v0.3"), ("nemotron-nano-9b-v2", "Nemotron-Nano-9B-v2"),
          ("phi4-14b", "Phi-4"), ("qwen3.8-27b", "Qwen3.8-27B")]
ROWS = [("bf16", "BF16"), ("nvfp4", "NVFP4"), ("fo6", "FourOverSix"), ("focus", "FOCUS"), ("gptq", "GPTQ‡"),
        ("if4", "IF4†"), ("zou", "MixFP4†"), ("fq-8x64", "FlipQuant 8x64"), ("fq-16x64", "FlipQuant 16x64"),
        ("fq-256x64", "FlipQuant 256x64")]
TASKS = [("piqa", "PIQA"), ("hellaswag", "HellaSwag"), ("winogrande", "WinoGrande"), ("arc_easy", "ARC-e"),
         ("arc_challenge", "ARC-c"), ("lambada_openai", "LAMBADA")]


def table(header, rows):
    """rows: [(label, [raw values])]. Each value is rounded once to two decimals; in every column, the best quantized
    value (every row but BF16) is bold, ties after rounding included."""
    shown = [(label, [f"{v:.2f}" for v in vals]) for label, vals in rows]
    best = [max(float(s[j]) for label, s in shown if label != "BF16") for j in range(len(header) - 1)]
    out = ["| " + " | ".join(header) + " |", "|---|" + "---:|" * (len(header) - 1)]
    for label, s in shown:
        cells = [f"**{c}**" if label != "BF16" and float(c) == best[j] else c for j, c in enumerate(s)]
        out.append(f"| {label} | " + " | ".join(cells) + " |")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qwen3-commit", required=True, help="the paper-eval commit holding X2's zeroshot6_qwen3.json")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    def show(commit, path):
        return json.loads(subprocess.run(["git", "-C", str(REPO), "show", f"{commit}:{path}"], capture_output=True,
                                         text=True, check=True).stdout)["models"]
    rec = dict(show(SOURCE_COMMIT, SOURCE), **show(args.qwen3_commit, QWEN3_SOURCE))
    md = ["# Zero-shot accuracy: six tasks, eight models, ten rows", "",
          "- Six zero-shot tasks on the eight paper models, ten rows each; accuracy in %. Every number comes from "
          "NVFP4-RaZeR paper-eval:",
          f"  - part X's six models: {SOURCE_COMMIT}, `{SOURCE}`;",
          f"  - Qwen3-1.7B and Qwen3-8B (part X amendment 2, the same protocol): {args.qwen3_commit}, `{QWEN3_SOURCE}`.",
          "  - The full reports, with the paired McNemar tests, are `results/paper_eval/zeroshot6/REPORT.md` and "
          "`results/paper_eval/zeroshot6_qwen3/REPORT.md` there.",
          "- Settings: lm-eval 0.4.11, 0-shot. acc_norm for PIQA, HellaSwag, ARC-e and ARC-c; acc for WinoGrande and "
          "LAMBADA (lambada_openai, pinned 900124bf). Batch 16 (Qwen3.8-27B: 8). Per-token activations. Native on the "
          "RTX PRO 6000 (build_V); IF4 and MixFP4 are simulated.",
          "- Harness: flipquant main 3db0072 `evaluation/downstream.py`, shown bit-identical to NVFP4-RaZeR's "
          "`run_lmeval_deploy.py` in step 0 (paper-eval `results/paper_eval/zeroshot6/STEP0.md`).",
          "- Bold: the best quantized value per column (BF16 excluded), after rounding to two decimals; ties are all bold.",
          ""]
    for key, title in MODELS:
        md += [f"## {title}", ""]
        rows = [(label, [rec[key][row]["acc"][t] for t, _ in TASKS] + [rec[key][row]["avg"]]) for row, label in ROWS]
        md += table(["Method"] + [n for _, n in TASKS] + ["Avg."], rows) + [""]
    md += ["## Summary: six-task Avg. per model", ""]
    rows = []
    for row, label in ROWS:
        avgs = [rec[key][row]["avg"] for key, _ in MODELS]
        rows.append((label, avgs + [sum(avgs) / len(avgs)]))
    md += table(["Method"] + [t for _, t in MODELS] + ["Mean"], rows)
    md += ["", "Mean = the unweighted mean over the eight models.", "",
           "‡ GPTQ-quantized NVFP4 weights (BF16-activation calibration) with FourOverSix activations.  ",
           "† Simulated (needs new hardware).", "",
           f"Generated by NVFP4-RaZeR paper-eval `experiments/paper_eval/zs6_flipquant_readme.py` from `{SOURCE}` at "
           f"{SOURCE_COMMIT} and `{QWEN3_SOURCE}` at {args.qwen3_commit}."]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
