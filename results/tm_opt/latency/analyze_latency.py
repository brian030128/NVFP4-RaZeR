"""R2 tables (PROTOCOL_QR.md): prefill latency, overheads and the profiler decomposition on the SM120 kernels.

Reads results_r2/bench/<model>/<label>_r<round>.json (bench_latency.py). Per (model, policy, shape): the median of
the per-round medians and their min-max over the 5 rounds. Overheads are paired within a round (policy / baseline
- 1 in the same round, whose policy order was shuffled), then summarized by the median and min-max over rounds.
Baselines: NVFP4 and FourOverSix on stock_wA (the deployment placement) for every map; for the 8x64 maps (weights
on B) also the placement-matched NVFP4 and FourOverSix on stock_wB.

python results/tm_opt/latency/analyze_latency.py [RESULTS_DIR]   -> latency.{json,md}
"""
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
O = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/home/dev/n16k64_campaign/sm120_bench/results_r2')
MODELS = (('llama8b', 'Llama-3.1-8B'), ('mistral7b', 'Mistral-7B-v0.3'), ('phi4', 'Phi-4'), ('qwen27b', 'Qwen3.8-27B'))
SHAPES = ('1x512', '1x2048', '4x2048')
MAPS = [f'{m}-{u}@{k}' for m in ('tmopt', 'tc') for u, k in (('8x64', 'n8k64_wB'), ('16x64', 'n16k64_wA'), ('256x64', 'n16k64_wA'))]
STOCK = ('nvfp4@stock_wA', 'fo6@stock_wA', 'nvfp4@stock_wB', 'fo6@stock_wB')
POLICIES = ('bf16',) + STOCK + tuple(MAPS)
CLASSES = ('FP4 GEMM (+ fused epilogue)', 'activation quantization', 'native linear, other', 'BF16 linear GEMM', 'lm_head (BF16)',
           'attention (SDPA, rotary, KV write)', 'linear attention (gated delta rule, conv1d)',
           'other (norms, MLP activation, embeddings, residual)')
NAMES = {'bf16': 'BF16', 'nvfp4@stock_wA': 'NVFP4 (stock_wA)', 'fo6@stock_wA': 'FourOverSix (stock_wA)',
         'nvfp4@stock_wB': 'NVFP4 (stock_wB)', 'fo6@stock_wB': 'FourOverSix (stock_wB)'}


def name(p):
    if p in NAMES:
        return NAMES[p]
    m, rest = p.split('-', 1)
    unit, kern = rest.split('@')
    return f"{'TM-OPT' if m == 'tmopt' else 'TM-OPT+TC'} {unit} ({kern}{', 16x64 granules' if unit == '256x64' else ''})"


def summary(values):
    return dict(median=statistics.median(values), min=min(values), max=max(values), n=len(values)) if values else None


def fmt_ms(s):
    return f"{s['median']:.2f} [{s['min']:.2f}–{s['max']:.2f}]" if s else '—'


def fmt_pct(s):
    return f"{100 * s['median']:+.2f}% [{100 * s['min']:+.2f}, {100 * s['max']:+.2f}]" if s else '—'


def baselines(p):
    out = ['nvfp4@stock_wA', 'fo6@stock_wA']
    if p.endswith('n8k64_wB'):
        out += ['nvfp4@stock_wB', 'fo6@stock_wB']
    return out


def main():
    out, md = {}, ['# R2 latency tables (generated by analyze_latency.py)', '']
    for model, title in MODELS:
        d = O / 'bench' / model
        runs = defaultdict(dict)
        for f in sorted(d.glob('*_r*.json')) if d.exists() else []:
            r = json.loads(f.read_text())
            runs[r['label']][r['round']] = r
        if not runs:
            continue
        rounds = sorted({k for v in runs.values() for k in v})
        res = dict(rounds=rounds, prefill={}, overhead={}, decomposition={}, class_delta={}, decode={}, memory={}, checks={})
        for p in POLICIES:
            if p not in runs:
                continue
            rr = runs[p]
            res['prefill'][p] = {s: summary([rr[k]['prefill'][s]['ms'] for k in rounds if k in rr and 'ms' in rr[k]['prefill'].get(s, {})]) for s in SHAPES}
            per_round = {s: [rr[k]['decomposition'][s] for k in rounds if k in rr and s in rr[k]['decomposition']] for s in SHAPES}
            for dd in (x for v in per_round.values() for x in v):
                dd['gpu_ms'].update(total=dd['gpu_ms_total'], gaps=dd['gaps_ms'], span=dd['device_span_ms']['median'])
            res['decomposition'][p] = {s: {c: summary([dd['gpu_ms'].get(c, 0.0) for dd in per_round[s]]) for c in CLASSES + ('total', 'gaps', 'span')}
                                       for s in SHAPES}
            res['memory'][p] = dict(weights_gib=rr[rounds[0]]['weights_gib'], peak_prefill_gib=max(rr[k]['peak_prefill_gib'] for k in rounds if k in rr))
            dec = defaultdict(list)
            for k in rounds:
                for mode, v in rr.get(k, {}).get('decode', {}).items():
                    if 'tokens_per_s' in v:
                        dec[mode].append(v['tokens_per_s'])
            res['decode'][p] = {mode: summary(v) for mode, v in dec.items()}
            if p != 'bf16':
                inst = rr[rounds[0]]['install']
                cov = rr[rounds[0]]['coverage']
                res['checks'][p] = dict(kernel=inst['kernel'], native_modules=inst['native_modules'], fallback=len(inst['fallback']),
                                        e0m3_tiles=inst['e0m3_tiles'], native_not_called=len(cov['native_not_called']),
                                        kernel_set=inst.get('kernel_set'))
        for p in MAPS + ['nvfp4@stock_wB', 'fo6@stock_wB', 'fo6@stock_wA', 'bf16']:
            if p not in runs:
                continue
            for b in (baselines(p) if p in MAPS else ['nvfp4@stock_wA', 'fo6@stock_wA']):
                if b == p or b not in runs:
                    continue
                for s in SHAPES:
                    ratios = [runs[p][k]['prefill'][s]['ms'] / runs[b][k]['prefill'][s]['ms'] - 1 for k in rounds
                              if k in runs[p] and k in runs[b] and 'ms' in runs[p][k]['prefill'][s] and 'ms' in runs[b][k]['prefill'][s]]
                    res['overhead'].setdefault(p, {}).setdefault(b, {})[s] = summary(ratios)
                    deltas = {}
                    for c in CLASSES:
                        v = [runs[p][k]['decomposition'][s]['gpu_ms'].get(c, 0.0) - runs[b][k]['decomposition'][s]['gpu_ms'].get(c, 0.0)
                             for k in rounds if k in runs[p] and k in runs[b] and s in runs[p][k]['decomposition'] and s in runs[b][k]['decomposition']]
                        if v and any(abs(x) > 0 for x in v):
                            deltas[c] = summary(v)
                    res['class_delta'].setdefault(p, {}).setdefault(b, {})[s] = deltas
        out[model] = res

        md += [f'## {title}', '', f'Rounds: {rounds}. Prefill latency in ms, median of the per-round medians [min–max over rounds].', '',
               '| policy | ' + ' | '.join(SHAPES) + ' | weights GiB | peak prefill GiB |', '|---|' + '---:|' * (len(SHAPES) + 2)]
        for p in POLICIES:
            if p in res['prefill']:
                md.append(f"| {name(p)} | " + ' | '.join(fmt_ms(res['prefill'][p][s]) for s in SHAPES)
                          + f" | {res['memory'][p]['weights_gib']:.1f} | {res['memory'][p]['peak_prefill_gib']:.1f} |")
        md += ['', 'Overhead of each map, paired within rounds: median [min, max] over rounds.', '',
               '| map | baseline | ' + ' | '.join(SHAPES) + ' |', '|---|---|' + '---:|' * len(SHAPES)]
        for p in MAPS + ['fo6@stock_wA', 'nvfp4@stock_wB', 'fo6@stock_wB', 'bf16']:
            for b, v in res['overhead'].get(p, {}).items():
                md.append(f'| {name(p)} | {name(b)} | ' + ' | '.join(fmt_pct(v[s]) for s in SHAPES) + ' |')
        for s in ('4x2048', '1x2048'):
            md += ['', f'GPU time per forward by class at {s} (ms, median over rounds); span = first kernel start to last kernel end.', '',
                   '| policy | FP4 GEMM | act. quant | BF16 linear | lm_head | attention | linear attn. | other | total kernels | span | gaps |',
                   '|---|' + '---:|' * 10]
            for p in POLICIES:
                if p not in res['decomposition'] or res['decomposition'][p][s]['total'] is None:
                    continue
                dd = res['decomposition'][p][s]
                cell = lambda c: f"{dd[c]['median']:.2f}" if dd[c] and dd[c]['median'] else '—'  # noqa: E731
                md.append(f"| {name(p)} | {cell(CLASSES[0])} | {cell(CLASSES[1])} | {cell(CLASSES[3])} | {cell(CLASSES[4])} | {cell(CLASSES[5])} | "
                          f"{cell(CLASSES[6])} | {cell(CLASSES[7])} | {cell('total')} | {cell('span')} | {cell('gaps')} |")
        md += ['', 'Per-class GPU-time change vs the baseline at 4x2048 (ms per forward, paired within rounds, median; classes that changed).', '',
               '| map | baseline | FP4 GEMM (mixed-kernel overhead) | act. quant | other classes |', '|---|---|---:|---:|---|']
        for p in MAPS:
            for b, v in res['class_delta'].get(p, {}).items():
                dv = v.get('4x2048', {})
                g, q = dv.get(CLASSES[0]), dv.get(CLASSES[1])
                base_g = res['decomposition'][b]['4x2048'][CLASSES[0]]
                rest = ', '.join(f"{c.split(' (')[0]} {x['median']:+.2f}" for c, x in dv.items() if c not in CLASSES[:2])
                md.append(f"| {name(p)} | {name(b)} | {g['median']:+.2f} ({100 * g['median'] / base_g['median']:+.1f}%) | "
                          f"{q['median']:+.2f} | {rest or '—'} |" if g and q and base_g else f'| {name(p)} | {name(b)} | — | — | {rest or "—"} |')
        if any(res['decode'].get(p) for p in POLICIES):
            md += ['', 'Decode, batch 1, 512-token prompt, 64 tokens (tokens/s, median [min–max] over rounds).', '',
                   '| policy | eager | CUDA graph |', '|---|---:|---:|']
            for p in POLICIES:
                dv = res['decode'].get(p, {})
                f = lambda s: f"{s['median']:.1f} [{s['min']:.1f}–{s['max']:.1f}]" if s else '—'  # noqa: E731
                md.append(f"| {name(p)} | {f(dv.get('eager_b1'))} | {f(dv.get('graph_b1'))} |")
        md += ['', 'Install checks (first round): ' + json.dumps({name(p): {k: v for k, v in c.items() if k != 'kernel_set'} for p, c in res['checks'].items()}), '']
    (HERE / 'latency.json').write_text(json.dumps(out, indent=1) + '\n')
    (HERE / 'latency.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
