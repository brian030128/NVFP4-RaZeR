"""Task 2 tables (results/scale_additivity/PROTOCOL.md): does scale training add to TM-OPT+TC, or cancel it?

Reads the NativeLinear (c) evaluation (runs/llama8b/report.json, run_ppl_deploy.py) and the calibration runs. Labels:
FourOverSix, NVFP4, BF16, scale, ours-<u>, scale_ours-<u>, ours_scale-<u> for u in 16x64, 8x64.
- Paired ΔNLL ± 2 SE: SCALE − FourOverSix, OURS − SCALE, and each combination against each single method.
- Additivity: I = X − SCALE − OURS + FourOverSix per window (the combined gain minus the sum of the single gains).
- The rule registered in advance:
  - additive: X is better than both single methods and I is n.s.;
  - partially overlapping: X is better than the better single method, but I > 0 significantly;
  - cancelling: X is not better than the better single method.
- Costs follow Task 1's definition; the E0M3 tiles and moved scales come from the calibration runs and the exporter.

python results/scale_additivity/analyze.py   -> additivity.{json,md}
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'tm_opt'))
from analyze_items import paired  # noqa: E402

RUNS = HERE / 'runs'
D = ('wiki', 'c4')
UNITS = ('16x64', '8x64')
V = {'significantly better': 'better', 'significantly worse': 'worse', 'not significantly different': 'n.s.'}


def load(p):
    return json.loads(Path(p).read_text())


def nll(ev, label):
    return {d: ev[label]['evaluation'][d]['nll'] for d in D}


def fmt(p):
    return f"{p['mean']:+.5f} ± {p['two_se']:.5f} ({V[p['verdict']]})"


def phases(report):
    # run_cost_distill.py stores the monitor summary as 'resources'; run_train_map.py under resources['phases']
    res = report['resources']
    return res['by_phase'] if 'by_phase' in res else res['phases']['by_phase']


INCLUDED = ('model_load', 'data_load', 'teacher_precompute', 'candidate_packing', 'preparation', 'training', 'write_output',
            'save_state')


def calibration_cost(report):
    return sum(v['seconds'] for k, v in phases(report).items() if k in INCLUDED)


def calibration_memory(report):
    """(peak GPU allocated GiB, peak host RSS GiB) over the included phases (Task 1's definition)."""
    inc = [v for k, v in phases(report).items() if k in INCLUDED]
    return max(v['gpu_peak_allocated_gib'][0] for v in inc), max(v['host_peak_rss_gib'] for v in inc)


def verdict(x_vs_best, x_vs_other, interaction):
    """The rule registered in PROTOCOL.md. The ΔNLLs are negative for gains, so I > 0 means that the combined gain is
    smaller than the sum of the single gains (paired(I, 0) reads 'significantly worse')."""
    if x_vs_best['verdict'] != 'significantly better':
        return 'cancelling'
    if interaction['verdict'] == 'significantly worse':
        return 'partially overlapping'
    if interaction['verdict'] == 'significantly better':
        return 'more than additive'
    return 'additive' if x_vs_other['verdict'] == 'significantly better' else 'additive (n.s. vs the weaker single method)'


def main():
    ev = load(RUNS / 'llama8b' / 'report.json')['evaluations']
    out = dict(ppl={k: {d: v['evaluation'][d]['ppl'] for d in D} for k, v in ev.items()}, units={})
    # the reference policies must reproduce the Parts 2-3 evaluation window for window (same artifacts, same windows)
    parts23 = load(HERE.parent / 'deploy_eval' / 'runs' / 'llama8b' / 'report.json')['evaluations']
    same = {k: all(ev[k]['evaluation'][d]['nll'] == parts23[p]['evaluation'][d]['nll'] for d in D)
            for k, p in (('BF16', 'BF16'), ('FourOverSix', 'FourOverSix'), ('NVFP4', 'NVFP4'), ('ours-16x64', 'tc-16x64'),
                         ('ours-8x64', 'tc-8x64')) if k in ev}
    out['reproduces_parts23'] = same
    md = ['# Scale training and TM-OPT+TC on Llama-3.1-8B (generated by analyze.py)', '',
          'NativeLinear (c), WikiText-2 / C4; paired ΔNLL ± 2 SE per window.', '',
          'Reference policies equal to the Parts 2-3 evaluation, every window\'s NLL: ' +
          ', '.join(f"{k} {'yes' if v else '**no**'}" for k, v in same.items()) + '.', '',
          '| arm | WikiText-2 | C4 |', '|---|---:|---:|']
    for k in ('BF16', 'NVFP4', 'FourOverSix', 'scale') + tuple(f'{a}-{u}' for u in UNITS for a in ('ours', 'scale_ours', 'ours_scale')):
        if k in ev:
            md.append(f"| {k} | {out['ppl'][k]['wiki']:.4f} | {out['ppl'][k]['c4']:.4f} |")
    F, S = nll(ev, 'FourOverSix'), nll(ev, 'scale')
    for u in UNITS:
        O = nll(ev, f'ours-{u}')
        res = dict(comparisons={}, additivity={})
        pairs = {'SCALE − FourOverSix': ('scale', 'FourOverSix'), 'SCALE − NVFP4': ('scale', 'NVFP4'),
                 'OURS − FourOverSix': (f'ours-{u}', 'FourOverSix'), 'OURS − SCALE': (f'ours-{u}', 'scale')}
        for x in ('scale_ours', 'ours_scale'):
            lab = f'{x}-{u}'
            if lab not in ev:
                continue
            pairs.update({f'{lab} − FourOverSix': (lab, 'FourOverSix'), f'{lab} − SCALE': (lab, 'scale'),
                          f'{lab} − OURS': (lab, f'ours-{u}')})
        for name, (a, b) in pairs.items():
            res['comparisons'][name] = {d: paired(nll(ev, a)[d], nll(ev, b)[d]) for d in D}
        for x in ('scale_ours', 'ours_scale'):
            lab = f'{x}-{u}'
            if lab not in ev:
                continue
            X = nll(ev, lab)
            inter = {d: paired([x_ - s - o + f for x_, s, o, f in zip(X[d], S[d], O[d], F[d])], [0.0] * len(F[d])) for d in D}
            row = dict(interaction=inter, verdict={})
            for d in D:
                vs_s, vs_o = res['comparisons'][f'{lab} − SCALE'][d], res['comparisons'][f'{lab} − OURS'][d]
                gain_s, gain_o = -res['comparisons']['SCALE − FourOverSix'][d]['mean'], -res['comparisons']['OURS − FourOverSix'][d]['mean']
                best, other = (vs_s, vs_o) if gain_s >= gain_o else (vs_o, vs_s)
                row['verdict'][d] = verdict(best, other, inter[d])
                row.setdefault('gains', {})[d] = dict(scale=gain_s, ours=gain_o, sum=gain_s + gain_o,
                                                      combined=-res['comparisons'][f'{lab} − FourOverSix'][d]['mean'])
            res['additivity'][lab] = row
        out['units'][u] = res
        md += ['', f'## {u}', '', '| comparison | WikiText-2 | C4 |', '|---|---|---|']
        for name, p in res['comparisons'].items():
            md.append(f"| {name} | {fmt(p['wiki'])} | {fmt(p['c4'])} |")
        md += ['', '| combination | corpus | gain SCALE | gain OURS | sum | combined gain | interaction I (± 2 SE) | reading |',
               '|---|---|---:|---:|---:|---:|---|---|']
        for lab, row in res['additivity'].items():
            for d in D:
                g = row['gains'][d]
                md.append(f"| {lab} | {d} | {g['scale']:+.5f} | {g['ours']:+.5f} | {g['sum']:+.5f} | {g['combined']:+.5f} | "
                          f"{fmt(row['interaction'][d])} | {row['verdict'][d]} |")
    # costs, tiles, moved scales
    costs, memory = {}, {}
    runs_all = {p.name: load(p / 'report.json') for p in RUNS.iterdir() if p.is_dir() and (p / 'report.json').exists() and p.name != 'llama8b'}
    runs = {k: v for k, v in runs_all.items() if not k.startswith('scale_dev_')}
    task1 = HERE.parent / 'nodev_cost' / 'runs'
    for name, r in runs.items():
        if r.get('status') == 'complete' and 'resources' in r:
            costs[name] = calibration_cost(r)
            memory[name] = calibration_memory(r)
    for u in UNITS:
        p = task1 / f'nd_tc_llama8b_{u}' / 'report.json'
        if p.exists():
            costs[f'ours-{u}'] = calibration_cost(load(p))
            memory[f'ours-{u}'] = calibration_memory(load(p))
    out['costs_seconds'] = costs
    # SCALE's learning rate (development set; method development, not counted in any cost)
    choice = load(RUNS / 'lr_choice.json') if (RUNS / 'lr_choice.json').exists() else None
    if choice:
        out['lr_choice'] = choice
        md += ['', '## SCALE learning rate (development set, 20 epochs; not part of any calibration cost)', '',
               '| learning rate | initial dev KL | final dev KL | run time |', '|---|---:|---:|---:|']
        for rate, kl in sorted(choice['final_dev_kl'].items(), key=lambda kv: float(kv[0])):
            r = runs_all.get(f'scale_dev_lr{rate}')
            t = sum(v['seconds'] for v in phases(r).values()) / 60 if r else float('nan')
            md.append(f"| {rate}{' (chosen)' if rate == choice['chosen'] else ''} | {choice['initial_dev_kl'][rate]:.5f} | {kl:.5f} | "
                      f"{t:.1f} min |")
    md += ['', '## Calibration cost (Task 1 definition) and tiles', '',
           'Memory: the maximum over the arm\'s calibration runs of peak GPU allocated / peak host RSS (sampled).', '',
           '| arm | calibration | peak GPU / host | E0M3 tiles | blocks whose scale moved |', '|---|---:|---:|---:|---|']
    arts = HERE / 'artifacts'
    for arm, parts in (('scale', ['scale_nodev']), *[(f'ours-{u}', [f'ours-{u}']) for u in UNITS],
                       *[(f'scale_ours-{u}', ['scale_nodev', f'scale_ours_{u}']) for u in UNITS],
                       *[(f'ours_scale-{u}', [f'ours-{u}', f'ours_scale_{u}']) for u in UNITS]):
        if not all(q in costs for q in parts):
            continue
        tiles = moved = '—'
        a = arts / arm / 'artifact.json'
        if arm.startswith('ours-'):          # OURS is the Parts 2-3 artifact
            a = HERE.parent / 'deploy_eval' / 'artifacts' / f"llama8b_tc_{arm.split('-')[1]}" / 'artifact.json'
        if a.exists():
            meta = load(a)
            tiles = f"{sum(m['e0m3_tiles'] for m in meta['modules']):,}"
            ls = meta['note']['record'].get('learned_scales')
            if ls:
                moved = f"{ls['blocks_scale_moved']:,} of {ls['blocks']:,} ({100 * ls['blocks_scale_moved'] / ls['blocks']:.1f} %)"
        gpu, host = max(memory[q][0] for q in parts), max(memory[q][1] for q in parts)
        md.append(f"| {arm} | {sum(costs[q] for q in parts) / 60:.1f} min ({' + '.join(parts)}) | {gpu:.1f} / {host:.1f} GiB | {tiles} | "
                  f"{moved} |")
    (HERE / 'additivity.json').write_text(json.dumps(out, indent=1) + '\n')
    (HERE / 'additivity.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
