"""Task 3: do lm-eval 0.4.5, 0.4.9.1 and 0.4.11 send the same requests to the model? CPU only, no model (READINESS.md).

Each version, in its own process, builds the suite's tasks from the pinned datasets (lm_eval_datasets.py) and the
requests of the first LIMIT documents (gsm8k: GSM8K_LIMIT). Few-shot seed 1234, as lm-eval's simple_evaluate
default. The request arguments are compared with 0.4.11's:
- loglikelihood: (context, continuation);
- generate_until: (context, generation kwargs).
These are the strings before tokenization. Tokenization (the BOS token) is HFLM's and is compared from the code
(READINESS.md).

    python results/lmeval_ready/compare_requests.py [LIMIT] [GSM8K_LIMIT]   -> requests.{json,md}
"""
import inspect
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
PY = sys.executable
PYDEPS = {'0.4.11': None, '0.4.9.1': '/home/dev/n16k64_campaign/lmeval_versions/lmeval049/pydeps',
          '0.4.5': '/home/dev/n16k64_campaign/lmeval045/pydeps'}
TASKS = ('arc_easy', 'arc_challenge', 'hellaswag', 'openbookqa', 'boolq', 'winogrande', 'piqa', 'gsm8k')


def dump(version, limit, gsm8k_limit, out):
    import lm_eval_compat  # noqa: F401  (0.4.5 and 0.4.9.1 under transformers 5)
    import lm_eval_datasets
    import lm_eval
    from lm_eval.tasks import TaskManager, get_task_dict
    import importlib.metadata as md
    got = md.version('lm_eval')
    assert got == version, (got, version, lm_eval.__file__)
    tm = TaskManager()
    result = dict(version=got, path=lm_eval.__file__, tasks={})
    for name in TASKS:
        task = get_task_dict([name], tm)[name]
        task.set_fewshot_seed(seed=1234)
        kwargs = dict(limit=gsm8k_limit if name == 'gsm8k' else limit, rank=0, world_size=1)
        accepted = inspect.signature(task.build_all_requests).parameters
        for k, v in dict(cache_requests=False, rewrite_requests_cache=False, system_instruction=None, apply_chat_template=False,
                         fewshot_as_multiturn=False, chat_template=None, tokenizer_name='').items():
            if k in accepted:
                kwargs[k] = v
        task.build_all_requests(**kwargs)
        rows = []
        for inst in task.instances:
            args = [a if isinstance(a, (str, int, float, bool, type(None))) else json.loads(json.dumps(a, default=str))
                    for a in inst.arguments]
            rows.append(dict(doc_id=inst.doc_id, idx=inst.idx, request_type=inst.request_type, arguments=args))
        result['tasks'][name] = dict(num_fewshot=task.config.num_fewshot, instances=rows)
    result['dataset_loads'] = lm_eval_datasets.LOADS
    Path(out).write_text(json.dumps(result) + '\n')


def main():
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 20
    gsm8k_limit = int(sys.argv[2]) if len(sys.argv) > 2 else 5
    tmp = HERE / 'requests_tmp'
    tmp.mkdir(exist_ok=True)
    dumps = {}
    for version, deps in PYDEPS.items():
        env = dict(os.environ, PYTHONPATH=os.pathsep.join(p for p in (deps, str(REPO)) if p), HF_HUB_OFFLINE='0')
        out = tmp / f'{version}.json'
        code = f'import sys; sys.argv = ["x"]; from results.lmeval_ready.compare_requests import dump; ' \
               f'dump({version!r}, {limit}, {gsm8k_limit}, {str(out)!r})'
        subprocess.run([PY, '-c', code], env=env, cwd=REPO, check=True)
        dumps[version] = json.loads(out.read_text())
    ref = dumps['0.4.11']
    report = dict(limit=limit, gsm8k_limit=gsm8k_limit, versions={v: d['path'] for v, d in dumps.items()}, tasks={})
    md = ['# lm-eval requests against 0.4.11 (generated by compare_requests.py)', '',
          f'First {limit} documents per task (gsm8k {gsm8k_limit}), few-shot seed 1234. Identical = every request\'s '
          'arguments (context, continuation / generation kwargs) are equal as strings.', '',
          '| task | requests (0.4.11) | ' + ' | '.join(v for v in dumps if v != '0.4.11') + ' |',
          '|---|---:|' + '---|' * (len(dumps) - 1)]
    for name in TASKS:
        a = ref['tasks'][name]['instances']
        row = dict(requests=len(a), num_fewshot=ref['tasks'][name]['num_fewshot'])
        cells = []
        for v, d in dumps.items():
            if v == '0.4.11':
                continue
            b = d['tasks'][name]['instances']
            same = len(a) == len(b) and all(x['arguments'] == y['arguments'] and x['doc_id'] == y['doc_id'] for x, y in zip(a, b))
            differing = [x['doc_id'] for x, y in zip(a, b) if x['arguments'] != y['arguments']]
            row[v] = dict(identical=same, requests=len(b), differing_doc_ids=sorted(set(differing))[:10])
            if not same:
                first = next(((x, y) for x, y in zip(a, b) if x['arguments'] != y['arguments']), None)
                row[v]['first_difference'] = None if first is None else dict(reference=first[0]['arguments'], other=first[1]['arguments'])
            cells.append('identical' if same else f"**differs** ({len(set(differing))} documents)")
        report['tasks'][name] = row
        md.append(f'| {name} | {len(a)} | ' + ' | '.join(cells) + ' |')
    report['dataset_loads'] = {v: d['dataset_loads'] for v, d in dumps.items()}
    (HERE / 'requests.json').write_text(json.dumps(report, indent=1) + '\n')
    (HERE / 'requests.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
