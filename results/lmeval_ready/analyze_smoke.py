"""Task 3 smoke tests (results/lmeval_ready/READINESS.md): downstream evaluation through HFLM, end to end.

Per model (runs/<model>/report.json, run_lmeval_deploy.py):
- the primary metric of every policy and task, against chance;
- NativeLinear (c) against fake (c) on the same examples: agreement and the accuracy difference;
- a determinism check: the repeated policy must give identical per-example results and gsm8k generations;
- native coverage: every quantized Linear ran natively, with no remaining BF16 Linear;
- runtime estimates: the model's seconds per request (loglikelihood / generate_until) times each task's full request
  count, plus the task's fixed time (building, scoring) as measured. Small subsets batch less well, so this is an
  upper estimate.

- per native policy and task, when recorded: the forwards by token-count bucket, the GEMM calls by CTA tile width
  and whether every quantized Linear ran in every forward (decode evidence for gsm8k).

python results/lmeval_ready/analyze_smoke.py [RUNS [STEM]]   -> STEM.{json,md} (default runs/, smoke)
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'runs'
STEM = sys.argv[2] if len(sys.argv) > 2 else 'smoke'
FULL = dict(arc_easy=2376, arc_challenge=1172, hellaswag=10042, openbookqa=500, boolq=3270, winogrande=1267, piqa=1838, gsm8k=1319)
PRIMARY = dict(arc_easy='acc_norm', arc_challenge='acc_norm', hellaswag='acc_norm', openbookqa='acc_norm', piqa='acc_norm',
               boolq='acc', winogrande='acc', gsm8k='exact_match')
TITLES = {'llama8b': 'Llama-3.1-8B', 'mistral7b': 'Mistral-7B-v0.3', 'phi4': 'Phi-4', 'qwen27b': 'Qwen3.8-27B'}


def metric(task_entry, task):
    m = task_entry['metrics']
    for key in (f'{PRIMARY[task]},none', f'{PRIMARY[task]},strict-match', f'{PRIMARY[task]},flexible-extract'):
        if key in m:
            return m[key]
    return None


def main():
    out, md = {}, ['# Downstream-evaluation smoke tests (generated by analyze_smoke.py)', '']
    for model, title in TITLES.items():
        p = RUNS / model / 'report.json'
        if not p.exists():
            continue
        r = json.loads(p.read_text())
        ev = r['evaluations']
        res = dict(versions=r['versions'], limit=r['limit'], gsm8k_limit=r['gsm8k_limit'], policies={}, native_vs_fake={}, repeat={},
                   coverage={}, estimates={})
        for lab, e in ev.items():
            res['policies'][lab] = {t: dict(value=metric(v, t), n=v['examples_evaluated'], seconds=v['seconds'],
                                            peak_gpu_gib=v['peak_gpu_allocated_gib'], chance=v['chance'])
                                    for t, v in e.get('tasks', {}).items()}
            if e.get('backend') == 'NativeLinear (c)':
                cov = e.get('coverage', {})
                res['coverage'][lab] = dict(native=cov.get('native'), native_called=cov.get('native_called'),
                                            remaining_bf16_linears=len(cov.get('remaining_bf16_linears', [])),
                                            fallback=len(e['install']['fallback']), kernel=e['install']['kernel'])
                gemm = {t: v['native_gemm'] for t, v in e.get('tasks', {}).items() if 'native_gemm' in v}
                if gemm:            # recorded by run_lmeval_deploy.py since the 8x64 smoke test
                    res.setdefault('native_gemm', {})[lab] = gemm
        for lab in ev:
            fake = f'{lab}-fake'
            if fake in ev and ev[lab].get('backend') == 'NativeLinear (c)':
                row = {}
                for t, v in ev[lab]['tasks'].items():
                    a, b = v['examples'], ev[fake]['tasks'][t]['examples']
                    keys = sorted(set(a) & set(b))
                    if t == 'gsm8k':
                        # identical = the same generated text; accuracy = strict-match exact match
                        same = sum(a[k]['raw'] == b[k]['raw'] for k in keys)
                        acc = [a[k]['strict-match']['exact_match'] for k in keys], [b[k]['strict-match']['exact_match'] for k in keys]
                    else:
                        same = sum(a[k] == b[k] for k in keys)
                        acc = [a[k] for k in keys], [b[k] for k in keys]
                    row[t] = dict(examples=len(keys), identical=same, native=sum(acc[0]) / len(keys), fake=sum(acc[1]) / len(keys))
                res['native_vs_fake'][lab] = row
        for lab in ev:
            rep = f'{lab}#repeat'
            if rep in ev:
                res['repeat'][lab] = {t: v['examples'] == ev[rep]['tasks'][t]['examples'] for t, v in ev[lab]['tasks'].items()}
        for lab, e in ev.items():
            if '#repeat' in lab:
                continue
            est = res['estimates'][lab] = {}
            for t, v in e.get('tasks', {}).items():
                n = v['examples_evaluated']
                if not n:
                    continue
                kind = 'generate_until' if t == 'gsm8k' else 'loglikelihood'
                mt = v.get('model_timing') or {}
                requests, model_s = mt.get(kind + '_requests'), mt.get(kind + '_seconds')
                if requests:
                    # model time scales with the requests; the rest (task building, scoring) is taken as fixed
                    full_s = model_s / requests * (requests / n) * FULL[t] + (v['seconds'] - model_s)
                    est[t] = dict(seconds_per_request=model_s / requests, requests_per_document=requests / n,
                                  fixed_seconds=v['seconds'] - model_s, full_hours=full_s / 3600, peak_gpu_gib=v['peak_gpu_allocated_gib'])
                else:
                    est[t] = dict(seconds_per_example=v['seconds'] / n, full_hours=v['seconds'] / n * FULL[t] / 3600,
                                  peak_gpu_gib=v['peak_gpu_allocated_gib'])
        out[model] = res
        md += [f'## {title}', '', f"lm-eval {r['versions']['lm_eval']}, transformers {r['versions']['transformers']}; "
               f"limit {r['limit']} per task, gsm8k {r['gsm8k_limit']}.", '',
               '| policy | ' + ' | '.join(FULL) + ' |', '|---|' + '---:|' * len(FULL)]
        for lab, pol in res['policies'].items():
            md.append(f'| {lab} | ' + ' | '.join('—' if t not in pol or pol[t]['value'] is None else f"{pol[t]['value']:.2f}" for t in FULL) + ' |')
        md += ['', 'NativeLinear (c) vs fake (c), same examples (identical correctness / gsm8k answers; accuracy native vs fake):', '']
        for lab, row in res['native_vs_fake'].items():
            md.append(f'- {lab}: ' + '; '.join(f"{t} {x['identical']}/{x['examples']} ({x['native']:.2f} vs {x['fake']:.2f})" for t, x in row.items()))
        md += ['', f"Rerun identical: {json.dumps(res['repeat'])}", f"Coverage: {json.dumps(res['coverage'])}", '']
        if res.get('native_gemm'):
            md += ['Native GEMMs per task (forwards by token-count bucket; GEMM calls by CTA tile width, auto sets only; '
                   'every quantized Linear in every forward):', '',
                   '| policy | kernel | task | forwards by tokens | calls by width | all Linears every forward |', '|---|---|---|---|---|---|']
            for lab, gemm in res['native_gemm'].items():
                for t, g in gemm.items():
                    fw = ', '.join(f'≤{b}: {c}' for b, c in sorted(g['forwards_by_token_bucket'].items(), key=lambda x: int(x[0])))
                    cw = '—' if g['calls_by_width'] is None else ', '.join(
                        f'{w}: {c}' for w, c in sorted(g['calls_by_width'].items(), key=lambda x: int(x[0])))
                    if g['calls_by_width'] is not None:
                        # every GEMM call picked a width (KernelSet.pick), so the widths must account for all calls
                        g['widths_cover_all_calls'] = sum(g['calls_by_width'].values()) == g['calls']
                        cw += '' if g['widths_cover_all_calls'] else ' (**not all calls**)'
                    md.append(f"| {lab} | {g['kernel']} | {t} | {fw} | {cw} | {'yes' if g['every_linear_every_forward'] else 'NO'} |")
            md.append('')
        md += [
               'Full-evaluation estimate (hours per task, from the smoke timings; peak GPU GiB):', '',
               '| policy | ' + ' | '.join(FULL) + ' | total |', '|---|' + '---:|' * (len(FULL) + 1)]
        for lab, est in res['estimates'].items():
            total = sum(v['full_hours'] for v in est.values())
            md.append(f'| {lab} | ' + ' | '.join(f"{est[t]['full_hours']:.2f}" if t in est else '—' for t in FULL) + f' | {total:.1f} |')
        md.append('')
    # the version cross-check on Llama BF16: lm-eval 0.4.5, 0.4.11 without BOS, and 0.4.11 as recommended (with BOS)
    runs = {name: RUNS / d / 'report.json' for name, d in (('0.4.5', 'xcheck_llama8b_045'), ('0.4.11 no BOS', 'xcheck_llama8b_0411_nobos'),
                                                             ('0.4.11', 'llama8b'))}
    if all(p.exists() for p in runs.values()):
        bf = {name: json.loads(p.read_text()) for name, p in runs.items()}
        tasks = {name: r['evaluations']['BF16']['tasks'] for name, r in bf.items()}

        def agree(x, y):
            row = {}
            for t in FULL:
                a, b = tasks[x].get(t, {}).get('examples', {}), tasks[y].get(t, {}).get('examples', {})
                keys = sorted(set(a) & set(b))
                if t == 'gsm8k':
                    same = sum(a[k]['raw'] == b[k]['raw'] for k in keys)
                else:
                    same = sum(a[k] == b[k] for k in keys)
                row[t] = dict(examples=len(keys), identical=same, values=[metric(tasks[x][t], t), metric(tasks[y][t], t)])
            return row
        xc = out['version_crosscheck'] = {'0.4.5 vs 0.4.11 no BOS': agree('0.4.5', '0.4.11 no BOS'),
                                          '0.4.11 no BOS vs 0.4.11': agree('0.4.11 no BOS', '0.4.11'),
                                          'tokenization': {name: r.get('tokenization') for name, r in bf.items()}}
        md += ['## Version cross-check (Llama-3.1-8B BF16)', '',
               'Per task: examples with identical results (correctness; gsm8k: generated text) / examples, and the two metric values.', '',
               '| comparison | ' + ' | '.join(FULL) + ' |', '|---|' + '---|' * len(FULL)]
        for name in ('0.4.5 vs 0.4.11 no BOS', '0.4.11 no BOS vs 0.4.11'):
            md.append(f'| {name} | ' + ' | '.join(f"{v['identical']}/{v['examples']} ({v['values'][0]:.2f} / {v['values'][1]:.2f})"
                                                  for v in xc[name].values()) + ' |')
        md += ['', f"Tokenization: {json.dumps(xc['tokenization'])}", '']
    (HERE / f'{STEM}.json').write_text(json.dumps(out, indent=1) + '\n')
    (HERE / f'{STEM}.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
