"""Qwen3.8-27B's Part R prefill latencies without and with the RTX PRO 6000 tile table (PROTOCOL.md).

Old: Part R's records (fallback widths), /home/dev/n16k64_campaign/sm120_bench/results_r2/bench/qwen27b/<label>_r<R>.json.
New: the same harness with the table, /home/dev/n16k64_campaign/tile_table/remeasure/qwen27b/<label>_r<R>.json.
Per policy and prefill shape: the median over the 5 rounds of the per-round median ms. The overheads are paired within
a round: TM-OPT+TC 16x64 / 256x64 (and TM-OPT) against FourOverSix and NVFP4 on stock_wA, median over rounds.

    python results/tile_table/compare_remeasure.py   -> remeasure.{json,md}
"""
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
OLD = Path('/home/dev/n16k64_campaign/sm120_bench/results_r2/bench/qwen27b')
NEW = Path('/home/dev/n16k64_campaign/tile_table/remeasure/qwen27b')
POLICIES = ('nvfp4@stock_wA', 'fo6@stock_wA', 'tmopt-16x64@n16k64_wA', 'tmopt-256x64@n16k64_wA', 'tc-16x64@n16k64_wA',
            'tc-256x64@n16k64_wA')
SPECS = ('1x512', '1x2048', '4x2048')


def load(base):
    out = {}
    for pol in POLICIES:
        for r in range(1, 6):
            p = base / f'{pol}_r{r}.json'
            if p.exists():
                out[(pol, r)] = json.loads(p.read_text())
    return out


def main():
    old, new = load(OLD), load(NEW)
    res = dict(latency_ms={}, overhead={}, table_source={})
    md = ['# Qwen3.8-27B Part R prefill latency without / with the tile table (generated by compare_remeasure.py)', '',
          'Median over 5 rounds of the per-round median ms (Part R harness, bench_latency.py). The table changes the 48x5120 '
          'linear-attention projections at T = 512 (128 -> 32) and T = 2048 (128 -> 64), and at T = 512 also 1024x5120 and '
          '6144x5120; nothing at T = 8192.', '', '| policy | ' + ' | '.join(f'{s} old | {s} new | change' for s in SPECS) + ' |',
          '|---|' + '---:|---:|---:|' * len(SPECS)]
    for pol in POLICIES:
        row = {}
        cells = []
        for s in SPECS:
            o = [old[(pol, r)]['prefill'][s]['ms'] for r in range(1, 6) if (pol, r) in old]
            n = [new[(pol, r)]['prefill'][s]['ms'] for r in range(1, 6) if (pol, r) in new]
            mo, mn = statistics.median(o), statistics.median(n)
            row[s] = dict(old=mo, new=mn, change_pct=100 * (mn / mo - 1), rounds_old=len(o), rounds_new=len(n))
            cells.append(f'{mo:.2f} | {mn:.2f} | {100 * (mn / mo - 1):+.2f} %')
        res['latency_ms'][pol] = row
        ks = [(new[(pol, r)].get('install') or {}).get('kernel_set') for r in range(1, 6) if (pol, r) in new]
        res['table_source'][pol] = sorted({(k or {}).get('table') for k in ks if k is not None} or {None})
        md.append(f'| {pol} | ' + ' | '.join(cells) + ' |')
    md += ['', 'Overhead paired within a round (median over rounds), old -> new:', '',
           '| map | vs | ' + ' | '.join(SPECS) + ' |', '|---|---|' + '---|' * len(SPECS)]
    for m in ('tc-16x64@n16k64_wA', 'tc-256x64@n16k64_wA', 'tmopt-16x64@n16k64_wA', 'tmopt-256x64@n16k64_wA'):
        for ref in ('fo6@stock_wA', 'nvfp4@stock_wA'):
            cells = []
            for s in SPECS:
                vals = {}
                for label, recs in (('old', old), ('new', new)):
                    x = [100 * (recs[(m, r)]['prefill'][s]['ms'] / recs[(ref, r)]['prefill'][s]['ms'] - 1)
                         for r in range(1, 6) if (m, r) in recs and (ref, r) in recs]
                    vals[label] = statistics.median(x)
                res['overhead'].setdefault(m, {}).setdefault(ref, {})[s] = vals
                cells.append(f"{vals['old']:+.2f} % -> {vals['new']:+.2f} %")
            md.append(f'| {m} | {ref} | ' + ' | '.join(cells) + ' |')
    md += ['', 'Table source recorded by the new runs: ' + json.dumps(res['table_source'])]
    (HERE / 'remeasure.json').write_text(json.dumps(res, indent=1) + '\n')
    (HERE / 'remeasure.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
