"""The RTX PRO 6000 tile table against the fallback rule (PROTOCOL.md).

Reads sm120/configs/<gpu_slug>.json (the table) and .raw.json (every width's CUPTI kernel time, median of 20 calls).
- Every (shape, bucket) where the table's width differs from select.fallback_width, per family, with the kernel time
  at the fallback width and at the table's width, and the gain.
- Where the mixed and stock families choose different widths.
- Part R's operating points: T = 1 (decode batch 1), 2048 (prefill 1x2048) and 8192 (4x2048), and also T = 512
  (1x512, in Part R's tables): does the table change any width there, for which models' shapes.

    python results/tile_table/analyze.py   -> tile_table.{json,md}
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / 'sm120'))
sys.path.insert(0, str(REPO / 'sm120' / 'bench'))
from mixfp4_sm120 import select as S  # noqa: E402

SLUG = 'nvidia_rtx_pro_6000_blackwell_workstation_edition'
MODELS = ('llama8b', 'mistral7b', 'phi4', 'qwen27b')
POINTS = {1: 'decode batch 1 (T = 1)', 512: 'prefill 1x512', 2048: 'prefill 1x2048', 8192: 'prefill 4x2048'}


def model_shapes():
    import common as B
    out = {}
    for m in MODELS:
        for proj, (n, k) in B.MODEL_SHAPES[m].items():
            out.setdefault(f'{n}x{k}', []).append(f'{m}.{proj}')
    return out


def main():
    cfg = REPO / 'sm120' / 'configs'
    table = json.loads((cfg / f'{SLUG}.json').read_text())
    raw = json.loads((cfg / f'{SLUG}.raw.json').read_text())['us']
    users = model_shapes()
    out = dict(gpu=table['meta']['gpu'].get('name'), kernels=table['meta']['kernels'], tags=table['meta'].get('tags'),
               departures={}, family_differences=[], operating_points={}, shapes=len(table['mixed']))
    md = ['# RTX PRO 6000 tile table vs the fallback rule (generated by analyze.py)', '',
          f"GPU {out['gpu']}; {out['shapes']} shapes x {len(S.BUCKETS)} buckets; kernel time = CUPTI median of 20 calls. "
          'The fallback is select.fallback_width: the narrowest width holding the tokens.', '']
    for fam in ('mixed', 'stock'):
        rows = []
        for shape, row in table[fam].items():
            for b, w in row.items():
                fb = S.fallback_width(int(b))
                if w != fb:
                    us = raw[fam][shape][b]
                    t_fb, t_w = us[str(fb)], us[str(w)]
                    rows.append(dict(shape=shape, bucket=int(b), fallback=fb, table=w, us_fallback=t_fb, us_table=t_w,
                                     gain_us=t_fb - t_w, gain_pct=100 * (t_fb - t_w) / t_fb, used_by=users.get(shape, [])))
        rows.sort(key=lambda r: (r['shape'], r['bucket']))
        out['departures'][fam] = rows
        md += [f'## {fam}: departures from the fallback ({len(rows)} of {out["shapes"] * len(S.BUCKETS)} (shape, bucket) cells)', '',
               '| shape (out x in) | T bucket | fallback | table | us fallback | us table | gain | used by |', '|---|---:|---:|---:|---:|---:|---:|---|']
        for r in rows:
            md.append(f"| {r['shape']} | {r['bucket']} | {r['fallback']} | {r['table']} | {r['us_fallback']:.2f} | {r['us_table']:.2f} | "
                      f"{r['gain_pct']:.1f} % | {', '.join(r['used_by'])} |")
        md.append('')
    for shape in table['mixed']:
        for b in table['mixed'][shape]:
            wm, ws = table['mixed'][shape][b], table['stock'][shape][b]
            if wm != ws:
                out['family_differences'].append(dict(shape=shape, bucket=int(b), mixed=wm, stock=ws, used_by=users.get(shape, [])))
    md += ['## Where mixed and stock choose different widths', '',
           '| shape | T bucket | mixed | stock | used by |', '|---|---:|---:|---:|---|']
    for r in out['family_differences']:
        md.append(f"| {r['shape']} | {r['bucket']} | {r['mixed']} | {r['stock']} | {', '.join(r['used_by'])} |")
    md += ['', "## Part R's operating points", '', '| point | family | changed (shape: fallback -> table) |', '|---|---|---|']
    for t, name in POINTS.items():
        b = str(S.bucket(t))
        for fam in ('mixed', 'stock'):
            changed = [(s, S.fallback_width(t), row[b]) for s, row in table[fam].items() if row[b] != S.fallback_width(t)]
            out['operating_points'].setdefault(name, {})[fam] = [dict(shape=s, fallback=f, table=w, used_by=users.get(s, []))
                                                                  for s, f, w in changed]
            md.append(f"| {name} | {fam} | {'none' if not changed else '; '.join(f'{s}: {f} -> {w}' for s, f, w in changed)} |")
    md += ['', 'The 8x64 policy (n8k64_wB) is a single build with no width variants; the table does not apply to it.']
    (HERE / 'tile_table.json').write_text(json.dumps(out, indent=1) + '\n')
    (HERE / 'tile_table.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
