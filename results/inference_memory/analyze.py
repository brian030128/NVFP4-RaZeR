"""Inference GPU memory tables (PROTOCOL.md), from runs/<model>/<policy>.json (measure_memory.py).

    python results/inference_memory/analyze.py   -> memory.{json,md}
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = HERE / 'runs'
GIB = 2 ** 30
MODELS = {'llama8b': 'Llama-3.1-8B', 'mistral7b': 'Mistral-7B-v0.3', 'phi4': 'Phi-4', 'qwen27b': 'Qwen3.8-27B'}
POLICIES = ('bf16', 'nvfp4@stock_wA', 'fo6@stock_wA', 'fo6@stock_wB', 'tc-8x64', 'tc-16x64', 'tc-256x64')
LABELS = {'bf16': 'BF16', 'nvfp4@stock_wA': 'NVFP4 (stock_wA)', 'fo6@stock_wA': 'FourOverSix (stock_wA)',
          'fo6@stock_wB': 'FourOverSix (stock_wB)', 'tc-8x64': 'TM-OPT+TC 8x64 (n8k64_wB)', 'tc-16x64': 'TM-OPT+TC 16x64 (auto)',
          'tc-256x64': 'TM-OPT+TC 256x64 (auto)'}
SAME_PLACEMENT = {'tc-16x64': ('fo6@stock_wA', 'nvfp4@stock_wA'), 'tc-256x64': ('fo6@stock_wA', 'nvfp4@stock_wA'),
                  'tc-8x64': ('fo6@stock_wB',)}
SCENARIOS = ('prefill_1x2048', 'prefill_4x2048', 'decode_b1')


def gib(x):
    return x / GIB


def main():
    out, md = {}, ['# Inference GPU memory (generated by analyze.py)', '']
    for model, title in MODELS.items():
        runs = {p: json.loads((RUNS / model / f'{p}.json').read_text()) for p in POLICIES if (RUNS / model / f'{p}.json').exists()}
        if not runs:
            continue
        res = out[model] = dict(policies={}, same_placement={})
        bf = runs.get('bf16')
        for p, r in runs.items():
            st = r['static']
            g = st['groups_bytes']
            dev = (r.get('install') or {}).get('report', {}).get('device_bytes', {})
            row = dict(allocated_gib=st['allocated_after_install_gib'], quantized_linears_bytes=g.get('quantized_linears', 0),
                       bf16_rest_bytes=sum(v for k, v in g.items() if k != 'quantized_linears'), groups=g, device_bytes=dev,
                       freed_check_difference_bytes=st.get('freed_check_difference_bytes'),
                       allocated_not_in_parameters_or_buffers_bytes=st.get('allocated_not_in_parameters_or_buffers_bytes'),
                       quantized_ratio_to_bf16=st.get('quantized_ratio_to_bf16'), model_ratio_to_bf16=st.get('model_ratio_to_bf16'),
                       kernel_workspace_bytes=r.get('kernel_workspace_bytes'), dynamic=r['dynamic'])
            res['policies'][p] = row
        for p, refs in SAME_PLACEMENT.items():
            if p not in runs:
                continue
            for ref in refs:
                if ref not in runs:
                    continue
                a, b = res['policies'][p], res['policies'][ref]
                res['same_placement'][f'{p} vs {ref}'] = dict(
                    installed_bytes_difference=a['quantized_linears_bytes'] - b['quantized_linears_bytes'],
                    device_bytes_equal=a['device_bytes'] == b['device_bytes'],
                    allocated_difference_bytes=int(round((a['allocated_gib'] - b['allocated_gib']) * GIB)),
                    peak_allocated_difference_bytes={s: int(round((a['dynamic'][s]['peak_allocated_gib'] - b['dynamic'][s]['peak_allocated_gib']) * GIB))
                                                     for s in SCENARIOS if 'error' not in a['dynamic'][s] and 'error' not in b['dynamic'][s]},
                    peak_reserved_difference_bytes={s: int(round((a['dynamic'][s]['peak_reserved_gib'] - b['dynamic'][s]['peak_reserved_gib']) * GIB))
                                                    for s in SCENARIOS if 'error' not in a['dynamic'][s] and 'error' not in b['dynamic'][s]})
        md += [f'## {title}', '',
               '| policy | quantized Linears | BF16 rest | allocated after install | ratio to BF16 (Linears / model) | '
               'prefill 1x2048 peak alloc / reserved | prefill 4x2048 peak alloc / reserved | decode b1 peak alloc / reserved |',
               '|---|---:|---:|---:|---|---:|---:|---:|']
        for p in POLICIES:
            if p not in res['policies']:
                continue
            x = res['policies'][p]
            ratio = '—' if x['quantized_ratio_to_bf16'] is None else f"{x['quantized_ratio_to_bf16']:.4f} / {x['model_ratio_to_bf16']:.4f}"
            dyn = []
            for s in SCENARIOS:
                d = x['dynamic'][s]
                dyn.append('OOM' if 'error' in d else f"{d['peak_allocated_gib']:.2f} / {d['peak_reserved_gib']:.2f}")
            md.append(f"| {LABELS[p]} | {gib(x['quantized_linears_bytes']):.3f} GiB | {gib(x['bf16_rest_bytes']):.3f} GiB | "
                      f"{x['allocated_gib']:.3f} GiB | {ratio} | " + ' | '.join(dyn) + ' |')
        q = res['policies'].get('tc-16x64') or next(iter(res['policies'].values()))
        md += ['', 'Checks and details:', '']
        for p in POLICIES:
            if p not in res['policies'] or p == 'bf16':
                continue
            x = res['policies'][p]
            md.append(f"- {LABELS[p]}: installed {x['device_bytes']}; freed check difference {x['freed_check_difference_bytes']} B; "
                      f"allocated outside parameters and buffers {x['allocated_not_in_parameters_or_buffers_bytes']} B; "
                      f"kernel workspaces {x['kernel_workspace_bytes']} B.")
        for name, c in res['same_placement'].items():
            md.append(f"- Same placement, {name}: installed bytes difference {c['installed_bytes_difference']} B "
                      f"(device_bytes equal: {c['device_bytes_equal']}); allocated difference {c['allocated_difference_bytes']} B; "
                      f"peak allocated difference {c['peak_allocated_difference_bytes']}; peak reserved difference {c['peak_reserved_difference_bytes']}.")
        d = q['dynamic']
        md += ['', f"KV cache (decode, prompt 2048 + 128): {gib(d['decode_b1'].get('cache_bytes', 0)):.3f} GiB "
               f"({d['decode_b1'].get('harness')}). Activation-quantization scratch per NativeLinear call, largest K: "
               f"prefill 1x2048 {d['prefill_1x2048'].get('scratch_bytes_max', 0) / 2 ** 20:.2f} MiB, 4x2048 "
               f"{d['prefill_4x2048'].get('scratch_bytes_max', 0) / 2 ** 20:.2f} MiB, decode {d['decode_b1'].get('scratch_bytes_max', 0) / 2 ** 10:.1f} KiB "
               '(one more is held by the quantization cache between calls). Logits: prefill 1x2048 '
               f"{gib(d['prefill_1x2048'].get('logits_bytes', 0)):.3f} GiB, 4x2048 {gib(d['prefill_4x2048'].get('logits_bytes', 0)):.3f} GiB.", '']
    (HERE / 'memory.json').write_text(json.dumps(out, indent=1) + '\n')
    (HERE / 'memory.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
