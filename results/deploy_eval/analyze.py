"""Parts 2-3 tables (results/deploy_eval/PROTOCOL.md): B3 ownership, and the deployment-path verification.

(i)   NativeLinear (c) - fake (c), per model x policy x corpus: paired per-window ΔNLL mean ± 2 SE; negligible means
      |mean| <= 2 SE in each cell (registered); max |ΔNLL|; PPL difference.
(ii)  ΔNLL(TM-OPT+TC - FourOverSix) and (- NVFP4) under NativeLinear (c) and under fake (c); does every map stay
      significantly better (mean + 2 SE < 0) under NativeLinear?
(iii) NativeLinear (c) - native (a), same maps (appendix, descriptive; (a) = the committed evaluations).
Wall time per model: NativeLinear (c) evaluation seconds per policy vs native (a) (the committed processes'
final_evaluation phase / their number of maps).

python results/deploy_eval/analyze.py [RUNS_DIR] [ARTIFACTS_DIR]   -> verification.{json,md}
"""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'tm_opt'))
from analyze_final import evaluations  # noqa: E402  (the committed native (a) evaluations, merged per model)
from analyze_items import R, load, paired  # noqa: E402

RUNS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'runs'
ARTIFACTS = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'artifacts'
DIAGNOSTICS = HERE / 'diagnostics'
M = R.parent.parent / 'mr_variants' / 'runs'
BF16 = {'llama8b': M / 'llama8b' / 'eval_bf16', 'mistral7b': M / 'mistral7b' / 'eval_bf16', 'phi4': M / 'phi4' / 'eval_bf16',
        'qwen27b': R / 'q_eval_bf16'}
MODELS = (('llama8b', 'Llama-3.1-8B'), ('mistral7b', 'Mistral-7B-v0.3'), ('phi4', 'Phi-4'), ('qwen27b', 'Qwen3.8-27B'))
D = ('wiki', 'c4')
MAPS = ('tc-8x64', 'tc-16x64', 'tc-256x64')
POLICIES = ('FourOverSix', 'NVFP4') + MAPS
NAMES = {'tc-8x64': 'TM-OPT+TC 8x64', 'tc-16x64': 'TM-OPT+TC 16x64', 'tc-256x64': 'TM-OPT+TC 256x64 (appendix)'}
ARTIFACT_OF = {'FourOverSix': 'fo6', 'NVFP4': 'nvfp4', 'tc-8x64': 'tc_8x64', 'tc-16x64': 'tc_16x64', 'tc-256x64': 'tc_256x64'}


def nll(ev, label):
    return {d: ev[label]['evaluation'][d]['nll'] for d in D}


def short(p):
    return {'significantly better': 'better', 'significantly worse': 'worse', 'not significantly different': 'n.s.'}[p['verdict']]


def fmt(p):
    return f"{p['mean']:+.5f} ± {p['two_se']:.5f} ({short(p)})"


def main():
    out, md = {}, ['# Deployment-path verification (generated by analyze.py)', '']
    b3 = []
    for model, title in MODELS:
        rp = RUNS / model / 'report.json'
        if not rp.exists():
            continue
        rep = load(rp)
        ev = rep['evaluations']
        res = dict(checks=dict(windows_equal_sm120_reference=rep['windows_equal_sm120_reference'],
                               data_validation=rep['data_validation'], status=rep['status']),
                   ppl={}, kernel={}, effects={}, convention={}, timing={}, ownership={}, export={})
        for lab in ('BF16',) + tuple(f'{p}-fake' for p in POLICIES) + POLICIES:
            if lab in ev:
                res['ppl'][lab] = {d: ev[lab]['evaluation'][d]['ppl'] for d in D}
        # (i) native (c) - fake (c)
        for p in POLICIES:
            if p in ev and f'{p}-fake' in ev:
                a, b = nll(ev, p), nll(ev, f'{p}-fake')
                res['kernel'][p] = {d: dict(paired(a[d], b[d]), max_abs=max(abs(x - y) for x, y in zip(a[d], b[d])),
                                            ppl_native=ev[p]['evaluation'][d]['ppl'], ppl_fake=ev[f'{p}-fake']['evaluation'][d]['ppl'],
                                            ppl_difference=ev[p]['evaluation'][d]['ppl'] - ev[f'{p}-fake']['evaluation'][d]['ppl'],
                                            negligible=abs(paired(a[d], b[d])['mean']) <= paired(a[d], b[d])['two_se'])
                                     for d in D}
        # (ii) effects under native (c) and fake (c)
        for m in MAPS:
            for base in ('FourOverSix', 'NVFP4'):
                row = {}
                for backend, suf in (('native (c)', ''), ('fake (c)', '-fake')):
                    if f'{m}{suf}' in ev and f'{base}{suf}' in ev:
                        row[backend] = {d: paired(nll(ev, f'{m}{suf}')[d], nll(ev, f'{base}{suf}')[d]) for d in D}
                if row:
                    res['effects'][f'{m} - {base}'] = row
        # (iii) native (c) - native (a)
        try:
            a_ev, a_checks = evaluations(model)
            a_nat = a_ev['native']
        except FileNotFoundError:
            a_nat, a_checks = {}, {}
        for p in POLICIES:
            if p in ev and p in a_nat:
                res['convention'][p] = {d: dict(paired(nll(ev, p)[d], nll(a_nat, p)[d]), ppl_c=ev[p]['evaluation'][d]['ppl'],
                                                ppl_a=a_nat[p]['evaluation'][d]['ppl']) for d in D}
        res['checks']['native_a_merge'] = a_checks
        # wall time
        res['timing'] = {lab: dict(evaluation_seconds=e.get('evaluation_seconds'), install_seconds=e.get('install_seconds'),
                                   backend=e.get('backend'), kernel=e.get('kernel')) for lab, e in ev.items()}
        a_procs = [R / 'q_eval_native'] if model == 'qwen27b' else [R / f'tc_{model}_eval_native']
        per_map = []
        for d in a_procs:
            r = load(d / 'report.json')
            ph = r['resources']['phases']['by_phase']
            per_map.append(dict(process=d.name, maps=len(r['evaluations']), final_evaluation_seconds=ph['final_evaluation']['seconds'],
                                candidate_packing_seconds=ph.get('candidate_packing', {}).get('seconds'),
                                per_map_seconds=ph['final_evaluation']['seconds'] / len(r['evaluations'])))
        res['timing_native_a'] = per_map
        # (iii) pairs windows across processes: the (a) process's windows must be these windows
        a_data = load(a_procs[0] / 'report.json')['data']
        res['checks']['windows_equal_native_a'] = {d: a_data[k]['token_sha256'] == rep['data'][k]['token_sha256']
                                                   for d, k in (('wiki', 'wiki'), ('c4', 'c4_paper'))}
        res['timing_meta'] = dict(load_seconds=rep.get('load_seconds'), data_seconds=rep.get('data_seconds'), total_seconds=rep.get('seconds'))
        # the evaluator reproduces the committed BF16 evaluation window by window (same windows, loading and NLL)
        old = load(BF16[model] / 'report.json')['evaluations']['BF16']['evaluation']
        res['checks']['bf16_window_nll_equal_committed'] = {d: ev['BF16']['evaluation'][d]['nll'] == old[d]['nll'] for d in D}
        # diagnostics of any significant (i) cell: its largest windows, the mean without the largest, layerwise runs
        res['diagnostics'] = {}
        for p, row in res['kernel'].items():
            for d in D:
                if row[d]['negligible']:
                    continue
                a, b = nll(ev, p)[d], nll(ev, f'{p}-fake')[d]
                diff = [x - y for x, y in zip(a, b)]
                order = sorted(range(len(diff)), key=lambda i: -abs(diff[i]))
                rest = [diff[i] for i in order[1:]]
                lw = {}
                for f in sorted(DIAGNOSTICS.glob(f"layerwise_{model}_{ARTIFACT_OF[p]}_{d}_w*.json")):
                    lw[f.stem] = {k: v for k, v in load(f)['summary'].items() if k != 'worst_native'}
                res['diagnostics'][f'{p} {d}'] = dict(
                    z=row[d]['mean'] / (row[d]['two_se'] / 2), median=sorted(diff)[len(diff) // 2],
                    positive=sum(x > 0 for x in diff), windows=len(diff), largest=[(i, diff[i]) for i in order[:3]],
                    without_largest=paired(rest, [0.0] * len(rest)), layerwise=lw)
        # B3 ownership and the exporter's checks
        for p in POLICIES:
            adir = ARTIFACTS / f'{model}_{ARTIFACT_OF[p]}'
            if (adir / 'ownership.json').exists():
                s = load(adir / 'ownership.json')['summary']
                res['ownership'][p] = s
                b3.append((title, p, s))
            if (adir / 'artifact.json').exists():
                note = load(adir / 'artifact.json')['note']
                rec = note.get('record', {})
                res['export'][p] = dict(candidates=rec.get('candidates'), weights_equal_calibration_record=rec.get('weights_equal_calibration_record'),
                                        export_seconds=note.get('export_seconds'), totals=rec.get('totals'), expansion=rec.get('expansion'))
        out[model] = res

        md += [f'## {title}', '', f"Checks: windows equal the SM120 reference {json.dumps(res['checks']['windows_equal_sm120_reference'])}; "
               f"data validation: {res['checks']['data_validation']}; native (a) merge: {json.dumps(a_checks)}.", '',
               '(i) NativeLinear (c) − fake (c), paired per window (registered: negligible ⇔ |mean| ≤ 2 SE in each cell).', '',
               '| policy | corpus | PPL native (c) | PPL fake (c) | ΔPPL | ΔNLL mean ± 2 SE | max |ΔNLL| | negligible |', '|---|---|---:|---:|---:|---|---:|---|']
        for p, row in res['kernel'].items():
            for d in D:
                x = row[d]
                md.append(f"| {NAMES.get(p, p)} | {d} | {x['ppl_native']:.4f} | {x['ppl_fake']:.4f} | {x['ppl_difference']:+.4f} | "
                          f"{x['mean']:+.6f} ± {x['two_se']:.6f} | {x['max_abs']:.5f} | {'yes' if x['negligible'] else '**NO**'} |")
        md += ['', '(ii) Effects, paired per window: native (c) and fake (c).', '',
               '| comparison | corpus | native (c) | fake (c) |', '|---|---|---|---|']
        for k, row in res['effects'].items():
            m, base = k.split(' - ')
            for d in D:
                n, f = row.get('native (c)', {}).get(d), row.get('fake (c)', {}).get(d)
                md.append(f"| {NAMES.get(m, m)} − {base} | {d} | {fmt(n) if n else '—'} | {fmt(f) if f else '—'} |")
        md += ['', '(iii) Convention effect (appendix, descriptive): NativeLinear (c) − native (a), paired per window.', '',
               '| policy | corpus | PPL (c) | PPL (a) | ΔNLL (c − a) |', '|---|---|---:|---:|---|']
        for p, row in res['convention'].items():
            for d in D:
                x = row[d]
                md.append(f"| {NAMES.get(p, p)} | {d} | {x['ppl_c']:.4f} | {x['ppl_a']:.4f} | {x['mean']:+.5f} ± {x['two_se']:.5f} |")
        for k, g in res['diagnostics'].items():
            p, d = k.split()
            lws = '; '.join(f"{name.split('_')[-1]}: native vs exact {v['native_vs_ref_mean']:.5f} (max {v['native_vs_ref_max']:.5f}), fake vs exact "
                            f"{v['fake_vs_ref_mean']:.5f} (max {v['fake_vs_ref_max']:.5f}), layers where native is worse {v['layers_native_worse_than_fake']}/"
                            f"{v['layers']}, activation codes bitwise {v['all_act_codes_bitwise']}" for name, v in g['layerwise'].items())
            md += ['', f"Diagnostics, {NAMES.get(p, p)} {d} (significant): z = {g['z']:+.2f}; median ΔNLL {g['median']:+.6f}; {g['positive']}/{g['windows']} "
                   f"windows positive; largest windows {[(i, round(x, 4)) for i, x in g['largest']]}; without the largest window "
                   f"{g['without_largest']['mean']:+.6f} ± {g['without_largest']['two_se']:.6f}." + (f' Layerwise ({lws}).' if lws else '')]
        tn = [v['evaluation_seconds'] for k, v in res['timing'].items() if v['backend'] == 'NativeLinear (c)' and v['evaluation_seconds']]
        tf = [v['evaluation_seconds'] for k, v in res['timing'].items() if v['backend'] == 'fake (c)' and v['evaluation_seconds']]
        ta = res['timing_native_a'][0]
        md += ['', f"Wall time per map: NativeLinear (c) {min(tn):.0f}–{max(tn):.0f} s (fake (c) {min(tf):.0f}–{max(tf):.0f} s) vs native (a) "
               f"≈ {ta['per_map_seconds']:.0f} s ({ta['process']}: {ta['final_evaluation_seconds']:.0f} s for {ta['maps']} maps, including the "
               f"window preparation once; its one-time candidate packing {ta['candidate_packing_seconds']:.0f} s)." if tn and tf else '', '']
    md += ['## B3: ownership check on every exported artifact', '',
           '| model | artifact | kernel | modules | elements checked | exact | format mismatches | E0M3 elements observed | tags = map |',
           '|---|---|---|---:|---:|---|---:|---:|---|']
    for title, p, s in b3:
        md.append(f"| {title} | {NAMES.get(p, p)} | {s['kernel']} | {s['modules']} | {s['informative_elements']:,} | {s['all_exact']} | "
                  f"{s['format_mismatches']} | {s['e0m3_elements_observed']:,} | {s.get('tags_equal_map', '— (no map)')} |")
    cells = [x['negligible'] for r in out.values() for row in r['kernel'].values() for x in row.values()]
    stays = {f"{m} - {base}": all(r['effects'].get(f'{m} - {base}', {}).get('native (c)', {}).get(d, {}).get('verdict') == 'significantly better'
                                  for r in out.values() for d in D) for m in MAPS for base in ('FourOverSix', 'NVFP4')}
    out['summary'] = dict(kernel_cells=len(cells), kernel_cells_negligible=sum(cells), maps_stay_better_under_native=stays)
    md[2:2] = [f"Summary: (i) {sum(cells)}/{len(cells)} kernel cells negligible; (ii) every map significantly better under NativeLinear: "
               f"{json.dumps(stays)}.", '']
    (HERE / 'verification.json').write_text(json.dumps(out, indent=1) + '\n')
    (HERE / 'verification.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
